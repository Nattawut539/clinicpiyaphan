CREATE TABLE clinic.users (
  user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(50) UNIQUE,
  email varchar(60) UNIQUE,
  password_hash text,
  role clinic.user_role NOT NULL DEFAULT 'user',
  google_id varchar(50) UNIQUE,
  line_id varchar(50) UNIQUE,
  created_at timestamp DEFAULT CURRENT_TIMESTAMP,
  last_login_at timestamp,
  account_status varchar(32) NOT NULL DEFAULT 'active',
  email_verified_at timestamptz,
  profile_completed_at timestamptz,
  medical_consent_at timestamptz,
  medical_consent_version text,
  registration_source varchar(32) NOT NULL DEFAULT 'local',
  status_reason text,
  status_changed_at timestamptz,
  status_changed_by integer REFERENCES clinic.users(user_id) ON DELETE SET NULL,
  deactivated_at timestamptz,
  session_version integer NOT NULL DEFAULT 1,
  CONSTRAINT users_email_format_chk CHECK
    (email IS NULL OR email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  CONSTRAINT users_account_status_chk CHECK
    (account_status IN ('active', 'pending_verification', 'deactivated',
                        'suspended', 'duplicate', 'unclaimed')),
  CONSTRAINT users_identity_chk CHECK
    (username IS NOT NULL OR email IS NOT NULL OR google_id IS NOT NULL OR line_id IS NOT NULL),
  CONSTRAINT users_auth_chk CHECK
    (password_hash IS NOT NULL OR google_id IS NOT NULL OR line_id IS NOT NULL
      OR (account_status = 'unclaimed' AND registration_source = 'walkin'))
);

