CREATE TABLE clinic.appointment_slot_templates (
  template_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  avaliable_date varchar(20) NOT NULL,
  hour_of_day smallint NOT NULL,
  UNIQUE (avaliable_date, hour_of_day),
  CONSTRAINT slot_template_period_chk CHECK
    ((avaliable_date = 'morning' AND hour_of_day BETWEEN 7 AND 10)
      OR (avaliable_date = 'afternoon' AND hour_of_day BETWEEN 16 AND 20))
);

CREATE TABLE clinic.appointment_slots (
  slot_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_date date NOT NULL,
  avaliable_date varchar(20) NOT NULL,
  hour_of_day smallint NOT NULL,
  template_id integer REFERENCES clinic.appointment_slot_templates(template_id),
  notes text,
  status clinic.slot_status NOT NULL DEFAULT 'open',
  start_ts timestamp GENERATED ALWAYS AS
    (service_date::timestamp + make_interval(hours => hour_of_day::integer)) STORED,
  bookable_until timestamp GENERATED ALWAYS AS
    (service_date::timestamp + make_interval(hours => hour_of_day::integer)
      + interval '30 minutes') STORED,
  UNIQUE (service_date, avaliable_date, hour_of_day),
  CONSTRAINT appointment_slot_period_chk CHECK
    ((avaliable_date = 'morning' AND hour_of_day BETWEEN 7 AND 10)
      OR (avaliable_date = 'afternoon' AND hour_of_day BETWEEN 16 AND 20))
);

CREATE INDEX appointment_slots_date_status_idx
  ON clinic.appointment_slots (service_date, status);

