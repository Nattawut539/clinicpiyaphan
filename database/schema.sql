CREATE OR REPLACE VIEW clinic.staff_profiles AS
SELECT u.user_id, u.role, d.first_name, d.last_name, d.position, d.license_no, d.phone
FROM clinic.users u
LEFT JOIN clinic.user_details d ON d.user_id = u.user_id
WHERE u.role IN ('super_admin', 'admin', 'doctor', 'assistant');

CREATE OR REPLACE VIEW clinic.faqs_public AS
SELECT help_id AS faq_id, title AS question, description AS answer,
       category, tags, updated_at
FROM clinic.help_requests
WHERE visibility = 'shared' AND request_status IN ('approved', 'resolved');

CREATE OR REPLACE VIEW clinic.slots_status_today AS
SELECT s.slot_id, s.service_date, s.avaliable_date, s.hour_of_day, s.status,
       s.start_ts, s.bookable_until,
       NOT EXISTS (
         SELECT 1 FROM clinic.appointments a
         WHERE a.slot_id = s.slot_id AND a.status NOT IN ('cancelled', 'rejected')
       ) AS is_empty,
       (s.status = 'open' AND now() <= s.bookable_until) AS is_bookable
FROM clinic.appointment_slots s
WHERE s.service_date = CURRENT_DATE;

CREATE OR REPLACE VIEW clinic.calendar_this_week AS
SELECT s.service_date AS date,
       count(*)::integer AS total_slots,
       count(a.appointment_id) FILTER
         (WHERE a.status NOT IN ('cancelled', 'rejected'))::integer AS booked_slots,
       (count(*) - count(a.appointment_id) FILTER
         (WHERE a.status NOT IN ('cancelled', 'rejected')))::integer AS available_slots,
       CASE WHEN bool_and(s.status = 'closed') THEN 'closed' ELSE 'open' END AS status
FROM clinic.appointment_slots s
LEFT JOIN clinic.appointments a ON a.slot_id = s.slot_id
WHERE s.service_date BETWEEN date_trunc('week', CURRENT_DATE)::date
                         AND (date_trunc('week', CURRENT_DATE)::date + 6)
GROUP BY s.service_date;

